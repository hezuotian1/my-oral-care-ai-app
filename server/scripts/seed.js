async function seedDemoUser() {
  const existing = await User.findOne({ phone: DEMO_PHONE })
  if (existing) {
    console.log(`演示账号已存在：${DEMO_PHONE}`)
    return
  }
  const hash = await bcrypt.hash(DEMO_PASSWORD, 10)
  await User.create({ realName: '演示用户', phone: DEMO_PHONE, password: hash, gender: 'unknown' })
  console.log(`已创建演示账号：${DEMO_PHONE} / ${DEMO_PASSWORD}`)
}

async function seedArticles() {
  let created = 0
  for (let i = 0; i < ARTICLES.length; i++) {
    const item = ARTICLES[i]
    const exists = await Article.findOne({ title: item.title })
    if (exists) continue
    await Article.create({ ...item, order: i })
    created++
  }
  console.log(`文章：新增 ${created} 篇，当前共 ${await Article.countDocuments()} 篇`)
}

async function main() {
  await mongoose.connect(process.env.MONGO_URI)
  console.log('MongoDB connected:', process.env.MONGO_URI)
  await seedDemoUser()
  await seedArticles()
  await mongoose.disconnect()
  console.log('种子数据完成')
}

main().catch((err) => {
  console.error('种子数据失败:', err.message)
  process.exit(1)
})
